    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        String Subno = jTextField2.getText().trim();

        // Validate input
        if (Subno.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please Enter Subject No to Delete", "INFORMATION", JOptionPane.INFORMATION_MESSAGE);
            return;
        }

        int confirm = JOptionPane.showConfirmDialog(this, "Are you sure you want to delete this Subject?", "CONFIRMATION", JOptionPane.YES_NO_OPTION);
        if (confirm == JOptionPane.YES_OPTION) {
            // Check for dependent rows in the class table
            String checkQuery = "SELECT * FROM `class` WHERE `subject_Subno` = ?";
            try (PreparedStatement psCheck = MySQL.getConnection().prepareStatement(checkQuery)) {
                psCheck.setString(1, Subno);
                try (ResultSet rs = psCheck.executeQuery()) {
                    if (rs.next()) {  // There are dependent rows
                        JOptionPane.showMessageDialog(this, "This Subject is referenced in the class table. You must delete or update the dependent records first.", "INFORMATION", JOptionPane.INFORMATION_MESSAGE);
                    } else {
                        // Proceed with the delete
                        String deleteQuery = "DELETE FROM `subject` WHERE `Subno` = ?";
                        try (PreparedStatement psDelete = MySQL.getConnection().prepareStatement(deleteQuery)) {
                            psDelete.setString(1, Subno);
                            int rowsDeleted = psDelete.executeUpdate();
                            if (rowsDeleted > 0) {
                                JOptionPane.showMessageDialog(this, "Subject deleted successfully.", "SUCCESS", JOptionPane.INFORMATION_MESSAGE);
                                loadSubject("Subno", "ASC", jTextField1.getText());
                                Reset();
                            } else {
                                JOptionPane.showMessageDialog(this, "No Subject found with the provided Subject No.", "INFORMATION", JOptionPane.INFORMATION_MESSAGE);
                            }
                        }
                    }
                } catch (SQLException e) {
                    JOptionPane.showMessageDialog(this, "An error occurred while checking for dependent records.", "ERROR", JOptionPane.ERROR_MESSAGE);
                    e.printStackTrace();
                }
            } catch (Exception ex) {
                ex.printStackTrace();
            }
        }      
    }//GEN-LAST:event_jButton3ActionPerformed

