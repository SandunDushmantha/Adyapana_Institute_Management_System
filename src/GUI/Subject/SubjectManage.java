    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String Subno = jTextField2.getText().trim();
        String Desc = jTextArea1.getText().trim();
        String Price = jTextField6.getText().trim();

        // Validate inputs
        if (Subno.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please Enter Subject No", "INFORMATION", JOptionPane.INFORMATION_MESSAGE);
            return;
        }
        if (Desc.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please Enter Description", "INFORMATION", JOptionPane.INFORMATION_MESSAGE);
            return;
        }
        if (Desc.length() > 150) {
            JOptionPane.showMessageDialog(this, "Description cannot be more than 150 characters.", "INFORMATION", JOptionPane.INFORMATION_MESSAGE);
            return;
        }
        if (Price.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please Enter Price", "INFORMATION", JOptionPane.INFORMATION_MESSAGE);
            return;
        }

        // Validate that the Price field contains only numeric values
        try {
            Double.parseDouble(Price);  // Check if the price can be parsed as a number
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Please enter a valid numeric value for Price.", "INFORMATION", JOptionPane.INFORMATION_MESSAGE);
            return;
        }

        // Check if the subject already exists
        try {
            String query = "SELECT * FROM `subject` WHERE `Subno` = ?";
            try (PreparedStatement ps = MySQL.getConnection().prepareStatement(query)) {
                ps.setString(1, Subno);
                ResultSet rs = ps.executeQuery();
                if (rs.next()) {
                    JOptionPane.showMessageDialog(this, "This Subject is Already Added.", "INFORMATION", JOptionPane.INFORMATION_MESSAGE);
                    return;
                }
            } catch (Exception e) {
                e.printStackTrace();
            }

            // Insert the new subject
            String query2 = "INSERT INTO `subject` (`Subno`, `Description`, `Price`) VALUES (?, ?, ?)";
            try (PreparedStatement insert = MySQL.getConnection().prepareStatement(query2)) {
                insert.setString(1, Subno);
                insert.setString(2, Desc);
                insert.setString(3, Price);
                insert.executeUpdate();
                JOptionPane.showMessageDialog(this, "This Subject is Added successfully.", "SUCCESS", JOptionPane.INFORMATION_MESSAGE);
                loadSubject("Subno", "ASC", jTextField1.getText());
                Reset();
            } catch (Exception e) {
                e.printStackTrace();
            }
        } catch (Exception e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "An error occurred while creating the subject. Please try again.", "ERROR", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButton1ActionPerformed

