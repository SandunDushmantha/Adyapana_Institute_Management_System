    private void jComboBox1ItemStateChanged(java.awt.event.ItemEvent evt) {//GEN-FIRST:event_jComboBox1ItemStateChanged
        // Only respond to selection (not deselection)
        if (evt.getStateChange() == ItemEvent.SELECTED) {
            String selectedItem = (String) jComboBox1.getSelectedItem();

            // Skip if "Select class" is chosen
            if ("Select class".equals(selectedItem)) {
                return;
            }

            // Extract the ClassNo from the combined string
            // The format is: "ClassNo / timeslot / teacher / subject / price"
            String classNo = selectedItem.split(" / ")[0];

            // Search using the class number
            loadClass("attendance.id", "ASC", classNo);
        }
    }//GEN-LAST:event_jComboBox1ItemStateChanged

    public void Reset() {
        // Get current date
        Calendar calendar = Calendar.getInstance();
        // OR using LocalDate (more modern approach)
        // LocalDate currentDate = LocalDate.now();

        jTextField1.setText("");
        jMonthChooser1.setMonth(calendar.get(Calendar.MONTH));  // Current month (0-based)
        jYearChooser1.setYear(calendar.get(Calendar.YEAR));     // Current year
        jComboBox1.setSelectedIndex(0);

        // Reload the table with default values
        loadClass("attendance.id", "ASC", "");
    }

