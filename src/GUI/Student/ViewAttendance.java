    private void loadClass(String column, String orderby, String searchText) {

        try {
            String query = "SELECT * FROM attendance INNER JOIN class ON class.ClassNo = attendance.class_ClassNo "
                    + "INNER JOIN subject ON subject.Subno = class.Subject_Subno "
                    + "INNER JOIN teacher ON teacher.Tno = class.teacher_Tno "
                    + "INNER JOIN student ON student.Sno = attendance.student_Sno "
                    + "INNER JOIN status ON status.id = attendance.status_id "
                    + "WHERE student.Sno LIKE ? OR class.ClassNo LIKE ? "
                    + "ORDER BY " + column + " " + orderby;

            PreparedStatement preparedStatement = MySQL.getConnection().prepareStatement(query);
            String searchPattern = "%" + searchText + "%";

            // Bind the same search pattern to all fields
            preparedStatement.setString(1, searchPattern);
            preparedStatement.setString(2, searchPattern);

            ResultSet resultSet = preparedStatement.executeQuery();

            DefaultTableModel defaultTableModel = (DefaultTableModel) jTable1.getModel();
            defaultTableModel.setRowCount(0);

            while (resultSet.next()) {
                Vector<String> row = new Vector<>();
                row.add(resultSet.getString("attendance.Date"));
                row.add(resultSet.getString("student.Sno"));
                row.add(resultSet.getString("student.Name"));
                row.add(resultSet.getString("teacher.Name"));
                row.add(resultSet.getString("class.ClassNo"));
                row.add(resultSet.getString("class.timeslot"));
                row.add(resultSet.getString("status.name"));

                defaultTableModel.addRow(row);
            }

        } catch (SQLException e) {
            e.printStackTrace();
        } catch (Exception ex) {
            ex.printStackTrace();
        }
    }

    private void loadClassByMonthAndYear(String column, String orderby, int month, int year) {
        try {
            String query = "SELECT * FROM attendance "
                    + "INNER JOIN class ON class.ClassNo = attendance.class_ClassNo "
                    + "INNER JOIN subject ON subject.Subno = class.Subject_Subno "
                    + "INNER JOIN teacher ON teacher.Tno = class.teacher_Tno "
                    + "INNER JOIN student ON student.Sno = attendance.student_Sno "
                    + "INNER JOIN status ON status.id = attendance.status_id "
                    + "WHERE MONTH(attendance.Date) = ? AND YEAR(attendance.Date) = ? "
                    + "ORDER BY " + column + " " + orderby;

            PreparedStatement preparedStatement = MySQL.getConnection().prepareStatement(query);
            preparedStatement.setInt(1, month);
            preparedStatement.setInt(2, year);

            ResultSet resultSet = preparedStatement.executeQuery();
            DefaultTableModel defaultTableModel = (DefaultTableModel) jTable1.getModel();
            defaultTableModel.setRowCount(0);

            while (resultSet.next()) {
                Vector<String> row = new Vector<>();
                row.add(resultSet.getString("attendance.Date"));
                row.add(resultSet.getString("student.Sno"));
                row.add(resultSet.getString("student.Name"));
                row.add(resultSet.getString("teacher.Name"));
                row.add(resultSet.getString("class.ClassNo"));
                row.add(resultSet.getString("class.timeslot"));
                row.add(resultSet.getString("status.name"));
                defaultTableModel.addRow(row);
            }
        } catch (SQLException e) {
            e.printStackTrace();
        } catch (Exception ex) {
            ex.printStackTrace();
        }
    }

    public void LoadClass() {

        try {
            String query = "SELECT * FROM class INNER JOIN teacher ON teacher.Tno = class.teacher_Tno "
                    + "INNER JOIN subject ON subject.Subno = class.subject_Subno";
            PreparedStatement ps = MySQL.getConnection().prepareStatement(query);
            ResultSet rs = ps.executeQuery();

            Vector<String> vector = new Vector();
            vector.add("Select class");

            while (rs.next()) {
                String ClassNo = rs.getString("ClassNo");
                String timeslot = rs.getString("timeslot");
                String teacher_Tno = rs.getString("teacher.Name");
                String subject_Subno = rs.getString("subject.Description");
                String Price = rs.getString("subject.Price");
                String combined = ClassNo + " / " + timeslot + " / " + teacher_Tno + " / " + subject_Subno + " / " + Price;

                vector.add(combined);

            }
            DefaultComboBoxModel model = new DefaultComboBoxModel(vector);
            jComboBox1.setModel(model);

        } catch (Exception e) {
            e.printStackTrace();
        }
    }
